/* 自定义计划：每行一段，"出处, 备注" 或 "出处\t备注"；也接受 JSON 数组 [{ref, note}] 或 [["出处","备注"]] */
function parsePlan(text){
  const t = (text || "").trim(); if (!t) return [];
  if (t[0] === "[") {
    try { const arr = JSON.parse(t); return arr.map(x => Array.isArray(x) ? [String(x[0] || ""), String(x[1] || "")] : [String(x.ref || x.passage || ""), String(x.note || "")]).filter(x => x[0]); } catch (e) { return []; }
  }
  return t.split(/\r?\n/).map(l => l.trim()).filter(Boolean).map(l => { const m = l.split(/\t|,|，/); return [m[0].trim(), (m.slice(1).join("，") || "").trim()]; }).filter(x => x[0]);
}

