/* 新城要理问答粘贴解析：接受官方中文页（“问题N：” 换行 问题 换行 答案）和英文（“Question N” / “Q1.” / “1.”）。
   返回 [{ n, q, a }]。 */
function parseCatechism(text){
  const lines = String(text || "").replace(/\r/g, "").split("\n").map(l => l.trim()).filter(Boolean);
  const out = []; let cur = null;
  const head = l => l.match(/^(?:问题|问|Question|Q)\s*(\d{1,2})\s*[.:：、]?\s*(.*)$/i) || l.match(/^(\d{1,2})\s*[.:：、]\s*(.*)$/);
  for (const l of lines) {
    const h = head(l);
    if (h) { if (cur) out.push(cur); cur = { n: +h[1], q: (h[2] || "").replace(/^答[：:]\s*/, "").trim(), a: "" }; continue; }
    if (!cur) continue;
    const t = l.replace(/^答[：:]\s*/, "");
    if (!cur.q) cur.q = t; else cur.a = cur.a ? cur.a + " " + t : t;
  }
  if (cur) out.push(cur);
  return out.filter(x => x.n >= 1 && x.n <= 52 && x.q);
}


