/** 月龄 → 年龄段；没填生日按 3–5 岁 */
function bandOf(months){
  if (months == null) return "prek";
  return months < 24 ? "baby" : months < 36 ? "toddler" : months < 60 ? "prek" : months < 108 ? "early" : months < 156 ? "mid" : "teen";
}
/** 某个状况在这个年龄段的内容：byBand 逐级回退（teen → mid → early → 基础） */
function contentFor(s, band){
  const chain = band === "teen" ? ["teen", "mid", "early"] : band === "mid" ? ["mid", "early"] : band === "early" ? ["early"] : [];
  const pick = f => { for (const b of chain) { const x = s.byBand && s.byBand[b] && s.byBand[b][f]; if (x) return x; } return s[f]; };
  return { why: (s.why && (s.why[band] || s.why.all)) || "", steps: pick("steps") || [], say: pick("say") || "", avoid: pick("avoid") || "", flag: s.flag || "" };
}
